#include <iostream>

int main() {

    // int
    int myNumber = 5;
    std::cout << myNumber << "\n";

    // double
    double myDouble = 5.6;
    std::cout << myDouble << "\n";

    // float
    float myFloat = 3.5f;
    std::cout << myFloat << "\n";

    // char
    /*
     * char must be used with single quote
     */
    char myChar = 'C';
    std::cout << myChar;

    // string
    std::string myString = "Hi, I'm Eduardo";
    std::cout << "\n" << myString << "\n";

    // boolean
    bool myBool = true;
    std::cout << myBool;

    return 0;
}
